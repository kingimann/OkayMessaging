import 'dart:io';

/// Builds the dashboard-paste copies of the Edge Functions.
///
/// The Supabase dashboard editor has no `_shared/` folder, so a function that
/// imports one fails to bundle ("Module not found"). These copies inline the
/// shared helpers. They used to be maintained by hand and drifted: the
/// platform fee still read 1.5% + 0¢ long after the shared helper moved to
/// 3.4% + 35¢, which would have deployed a fee below Stripe's own cut.
/// Generating them removes the chance of that happening twice — `flutter test`
/// fails if a copy on disk doesn't match what this produces.
///
/// Run after touching anything under `supabase/functions/`:
///
///     dart tool/paste_functions.dart

