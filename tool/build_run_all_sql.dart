import 'dart:io';

/// Generates `docs/run_all_sql.sql` — the whole schema as ONE paste.
///
/// **Why this exists.** The bundle used to be assembled by hand, once, with
/// no generator. It went stale immediately and silently: by the time anybody
/// checked it was missing THIRTY-ODD migrations, including load-bearing
/// security ones (`directory_phone_privacy.sql`, `moderation_scopes.sql`,
/// `audit_log_immutable.sql`). An owner pasting it would have got a partial
/// schema and no warning. A generator plus a test that the committed file
/// matches its output is the only thing that stops that happening again.
///
/// **The order is a dependency order, not alphabetical.** A function body is
/// parsed at CREATE time, so a file whose policy calls `is_locked_out` has to
/// come after the file that defines it; this repo has already shipped that
/// bug once. Most of the list below is taken verbatim from `tool/check_sql.sh`
/// — the order that is actually verified against a real Postgres — with the
/// files that check does not assert on slotted in where they belong.
