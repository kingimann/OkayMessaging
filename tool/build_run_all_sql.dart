/// Deliberately NOT in the bundle, each for a reason worth stating rather
/// than leaving somebody to wonder.
const Map<String, String> excluded = {
  'docs/run_all_sql.sql': 'this file',
  'docs/delete_numberless_accounts.sql':
      'destructive and one-off — deletes accounts, run deliberately or not '
          'at all',
  'docs/grant_owner.sql':
      'grants the owner role to one phone number, which has to be edited '
          'before it is run',
  'docs/verify_setup.sql':
      'a read-only check, not a migration — run it after this if you want '
          'the receipt',
};

const String outputPath = 'docs/run_all_sql.sql';

String build() {
  final b = StringBuffer()
    ..writeln('-- ${'=' * 74}')
    ..writeln('-- OkayMessenger — the whole schema, as one paste.')
    ..writeln('--')
    ..writeln('-- GENERATED by tool/build_run_all_sql.dart. Do not edit by '
        'hand: a test')
    ..writeln('-- fails if this file stops matching the generator, which is '
        'what stops it')
    ..writeln('-- going stale the way the hand-assembled version did (it '
        'silently fell')
    ..writeln('-- thirty-odd migrations behind, security ones included).')
    ..writeln('--')
    ..writeln('-- Paste the whole thing into the Supabase SQL editor and run '
        'it. Every')
    ..writeln('-- statement is idempotent (create-or-replace / if-not-exists '
        '/ drop-if-')
    ..writeln('-- exists), so re-running is safe and is how you apply '
        'whatever is new.')
    ..writeln('--')
    ..writeln('-- The ORDER matters and is not alphabetical: a function body '
        'is parsed at')
    ..writeln('-- CREATE time, so a policy calling is_locked_out has to come '
        'after the file')
    ..writeln('-- that defines it. It is the order tool/check_sql.sh verifies '
        'against a')
    ..writeln('-- real Postgres.')
    ..writeln('--')
    ..writeln('-- STILL A DASHBOARD STEP afterwards: create the Storage '
        'buckets')
    ..writeln('-- (chat-backups, market-media, voice-notes, public-media). '
        'The policies for')
    ..writeln('-- them are included here; the buckets themselves are not '
        'SQL.')
    ..writeln('--')
    ..writeln('-- NOT included, on purpose:');
  excluded.forEach((path, why) => b.writeln('--   $path — $why'));
  b
    ..writeln('-- ${'=' * 74}')
    ..writeln();

  for (final path in orderedFiles) {
    final file = File(path);
    if (!file.existsSync()) {
      stderr.writeln('missing: $path');
      exitCode = 1;
      continue;
    }
    b
      ..writeln()
      ..writeln('-- ${'#' * 68}')
      ..writeln('-- ## $path')
      ..writeln('-- ${'#' * 68}')
      ..writeln(file.readAsStringSync().trimRight())
      ..writeln();
  }
  return b.toString();
}

void main(List<String> args) {
  final text = build();
  if (args.contains('--check')) {
    final current =
        File(outputPath).existsSync() ? File(outputPath).readAsStringSync() : '';
    if (current != text) {
      stderr.writeln('$outputPath is stale — run: dart $outputPath');
      exitCode = 1;
      return;
    }
    stdout.writeln('$outputPath is up to date');
    return;
  }
  File(outputPath).writeAsStringSync(text);
  stdout.writeln('wrote $outputPath (${orderedFiles.length} files, '
      '${text.split('\n').length} lines)');
}
