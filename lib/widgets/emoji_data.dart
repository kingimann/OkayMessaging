  /// Emojis matching [query], by keyword or by category name ("food"). An
  /// empty query matches nothing, so callers show the categories instead.
  static List<String> search(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return const [];
    final out = <String>[];
    final seen = <String>{};
    for (final entry in categories.entries) {
      if (entry.key.toLowerCase().contains(q)) {
        for (final e in entry.value) {
          if (seen.add(e)) out.add(e);
        }
      }
    }
    for (final entry in _keywords.entries) {
      if (entry.value.split(' ').any((w) => w.startsWith(q)) &&
          seen.add(entry.key)) {
        out.add(entry.key);
      }
    }
    return out;
  }
